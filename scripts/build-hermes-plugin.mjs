#!/usr/bin/env node
/** Generate the native Hermes package from plugin-src/hermes and shared SLM assets. */
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'plugin-src', 'hermes');
const OUT = path.join(ROOT, 'hermes-plugin');
const CHECK = process.argv.includes('--check');
const managed = new Map();
const read = (file) => fs.readFileSync(file, 'utf8').replace(/\r\n?/g, '\n').replace(/\n*$/, '\n');
const put = (relative, content) => managed.set(path.join(OUT, relative), content);
// The plugin runs only with the SLM release it ships with, so that release is
// stamped from pyproject.toml here rather than kept by hand (it went stale).
const VERSION = (read(path.join(ROOT, 'pyproject.toml')).match(/^version = "(\d+)\.(\d+)\.(\d+)"$/m) || []).slice(1);
if (VERSION.length !== 3) { console.error('pyproject.toml has no x.y.z version'); process.exit(2); }
const stamp = (name, text) => {
  const rule = name === '__init__.py'
    ? [/^_RELEASE_SLM_VERSION = \(\d+, \d+, \d+\)$/m, `_RELEASE_SLM_VERSION = (${VERSION.join(', ')})`]
    : name === 'plugin.yaml' ? [/^version: .*$/m, `version: ${VERSION.join('.')}`] : null;
  if (!rule) return text;
  if (!rule[0].test(text)) { console.error(`${name}: no version line to stamp`); process.exit(2); }
  return text.replace(rule[0], rule[1]);
};
for (const name of ['plugin.yaml', 'README.md', '__init__.py', 'remote.py', 'command-inventory.json']) put(name, stamp(name, read(path.join(SRC, name))));

// L3-08: docs/hermes.md and the root README.md's Hermes section quote the
// pinned GitHub release in prose (install command, release tag, download
// URL) — not a generated template, so the loop above never touches them.
// A hand-kept number went stale (4.1.13 pinned for several releases).
// Stamped here too, from the same pyproject.toml version, so both the
// package and its install docs move together.
const stampHermesDocVersion = (text) => text
  .replace(/superlocalmemory==\d+\.\d+\.\d+/g, `superlocalmemory==${VERSION.join('.')}`)
  .replace(/`v\d+\.\d+\.\d+`/g, `\`v${VERSION.join('.')}\``)
  .replace(/download\/v\d+\.\d+\.\d+\//g, `download/v${VERSION.join('.')}/`)
  .replace(/SuperLocalMemory \d+\.\d+\.\d+ ships/g, `SuperLocalMemory ${VERSION.join('.')} ships`);
managed.set(path.join(ROOT, 'docs', 'hermes.md'), stampHermesDocVersion(read(path.join(ROOT, 'docs', 'hermes.md'))));
managed.set(path.join(ROOT, 'README.md'), stampHermesDocVersion(read(path.join(ROOT, 'README.md'))));
for (const group of ['skills', 'agents']) {
  const source = path.join(ROOT, group === 'skills' ? 'plugin-src/skills' : 'plugin-src/agents');
  for (const entry of fs.readdirSync(source, { withFileTypes: true })) {
    if (group === 'skills' && entry.isDirectory()) put(`skills/${entry.name}/SKILL.md`, read(path.join(source, entry.name, 'SKILL.md')));
    if (group === 'agents' && entry.isFile() && entry.name.endsWith('.md')) put(`agents/${entry.name}`, read(path.join(source, entry.name)));
  }
}
const banner = '# _GENERATED — DO NOT HAND-EDIT\n\nGenerated by scripts/build-hermes-plugin.mjs from plugin-src/hermes and plugin-src/{skills,agents}.\n';
put('_GENERATED.md', banner);
const stale = [];
const pycache = path.join(OUT, '__pycache__');
if (fs.existsSync(pycache)) {
  if (CHECK) stale.push(path.relative(ROOT, pycache));
  else fs.rmSync(pycache, { recursive: true, force: true });
}
for (const [target, contents] of managed) {
  if (!fs.existsSync(target) || read(target) !== contents) stale.push(path.relative(ROOT, target));
  if (!CHECK) { fs.mkdirSync(path.dirname(target), { recursive: true }); fs.writeFileSync(target, contents); }
}
if (CHECK && stale.length) { console.error(`Hermes plugin drift:\n${stale.join('\n')}`); process.exit(2); }
console.log(CHECK ? 'Hermes plugin in sync.' : `Generated ${managed.size} Hermes plugin files.`);
